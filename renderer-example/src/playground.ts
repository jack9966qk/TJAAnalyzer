// ── Rendering ──

let renderTimeout: ReturnType<typeof setTimeout> | null = null;

function scheduleRender(): void {
  if (renderTimeout) clearTimeout(renderTimeout);
  renderTimeout = setTimeout(doRender, 50);
}

function doRender(): void {
  const tja = tjaInput.value.trim();
  if (!tja) {
    statusText.textContent = "No TJA content";
    return;
  }

  statusText.textContent = "Rendering...";

  const start = performance.now();

  try {
    // Build partial ratios from current state (only include modified values)
    const layoutRatios: Partial<LayoutRatios> = {};
    let hasOverrides = false;
    for (const meta of RATIO_METAS) {
      if (currentRatios[meta.key] !== DEFAULT_LAYOUT_RATIOS[meta.key]) {
        layoutRatios[meta.key] = currentRatios[meta.key];
        hasOverrides = true;
      }
    }

    const course = optCourse.value ? { difficulty: optCourse.value } : undefined;

    // Resolve branch: "auto" shows all branches, otherwise show normal only
    let branch: BranchSelection = "auto";
    if (!optBranches.checked) {
      const info = getChartInfo(tja);
      const resolvedCourse = course ?? info.courseSpecifiers[0];
      if (resolvedCourse && info.hasBranching(resolvedCourse)) {
        branch = BranchName.Normal;
      }
    }

    createChartView(tja, canvas, course, {
      zoom: { beatsPerLine: parseInt(optBpl.value, 10) },
      branch,
      dpr: parseFloat(optDpr.value),
      showAttribution: optAttribution.checked,
      layoutRatios: hasOverrides ? layoutRatios : undefined,
    });

    const elapsed = performance.now() - start;
    statusText.textContent = "Rendered successfully";
    renderTimeEl.textContent = `${elapsed.toFixed(1)}ms`;
  } catch (err) {
    statusText.textContent = `Error: ${err instanceof Error ? err.message : String(err)}`;
    renderTimeEl.textContent = "";
    console.error("Render error:", err);
  }
}

